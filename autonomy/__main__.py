import argparse
import hashlib
import json
from pathlib import Path
import platform
import subprocess
import cryptography

from .demo import build_case
from .evidence import verify


def main():
    parser = argparse.ArgumentParser(description="AUT-001 synthetic independent-reversal reference model")
    sub = parser.add_subparsers(dest="command", required=True)
    demo = sub.add_parser("demo")
    demo.add_argument("--output", default="artifacts")
    check = sub.add_parser("verify")
    check.add_argument("bundle")
    check.add_argument("--registry")
    args = parser.parse_args()
    if args.command == "demo":
        bundle, registry, _ = build_case(args.output)
        result = verify(bundle, registry)
        root = Path(__file__).resolve().parents[1]
        try:
            commit = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=root, stderr=subprocess.DEVNULL, text=True).strip()
            dirty = bool(subprocess.check_output(["git", "status", "--porcelain"], cwd=root, text=True).strip())
        except (FileNotFoundError, subprocess.CalledProcessError):
            commit, dirty = None, True
        hashes = {p.relative_to(root).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
                  for folder in ("autonomy", "tests") for p in sorted((root / folder).glob("*.py"))}
        report = {"python": platform.python_version(), "cryptography": cryptography.__version__,
                  "source_commit": commit, "working_tree_dirty": dirty, "source_sha256": hashes,
                  "result": result, "key_custody": "All demo keys generated by one process; no independent institutions"}
        (Path(args.output) / "run-report.json").write_text(json.dumps(report, indent=2) + "\n")
    else:
        try:
            bundle = json.loads(Path(args.bundle).read_text())
            registry = json.loads(Path(args.registry).read_text()) if args.registry else None
            result = verify(bundle, registry)
        except (ValueError, OSError) as error:
            result = {"technical_verdict": "FAIL", "reason": str(error)}
    print(json.dumps(result, indent=2))
    return {"PASS": 0, "FAIL": 1, "UNRESOLVED": 2}[result["technical_verdict"]]


if __name__ == "__main__":
    raise SystemExit(main())
